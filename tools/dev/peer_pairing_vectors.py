#!/usr/bin/env python3
"""The server link's pairing vector (design/peers/link.md): an independent implementation of the peer card encoding,
the commitment, the SAS digest and code, and the rotation announcement's message, written to (or checked against)
core/test-assets/peer/pairing-vectors.json. PeerCryptoVectors (core/tests/unit/test_peer_crypto.cpp) asserts the same
file against peer::crypto, so the two can't drift; Vaulthalla Desktop implements its brokered check against it.

    tools/dev/peer_pairing_vectors.py --write   regenerate the file
    tools/dev/peer_pairing_vectors.py --check   recompute and compare (exit 1 on any difference)

Standard library only.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
VECTORS = REPO / "core" / "test-assets" / "peer" / "pairing-vectors.json"

CARD_DOMAIN = b"vh/peer/card/v1"
COMMIT_DOMAIN = b"vh/peer/commit/v1"
SAS_DOMAIN = b"vh/peer/sas/v1"
ROTATE_DOMAIN = b"vh/peer/rotate/v1"


def seq(start: int) -> bytes:
    return bytes(range(start, start + 32))


def fill(byte: int) -> bytes:
    return bytes([byte]) * 32


def lp(text: str) -> bytes:
    raw = text.encode("utf-8")
    return len(raw).to_bytes(4, "big") + raw


def card_bytes(card: dict) -> bytes:
    keys = [base64.b64decode(k) for k in card["attest_public_keys"]]
    out = CARD_DOMAIN + lp(card["node_id"]) + lp(card["name"]) + len(keys).to_bytes(4, "big")
    for k in keys:
        out += k
    out += base64.b64decode(card["wrap_public_key"])
    out += card["peer_protocol"].to_bytes(4, "big")
    out += lp(card["product_version"])
    return out


def sha(data: bytes) -> bytes:
    return hashlib.sha256(data).digest()


def code_of(digest: bytes) -> str:
    return f"{int.from_bytes(digest[:8], 'big') % 1_000_000:06d}"


def build() -> dict:
    b64 = lambda b: base64.b64encode(b).decode()  # noqa: E731
    inputs = {
        "spki_a": seq(0x00).hex(),
        "spki_b": seq(0x20).hex(),
        "nonce_a": seq(0x40).hex(),
        "nonce_b": seq(0x60).hex(),
        "card_a": {
            "node_id": "00000000-0000-4000-8000-00000000000a",
            "name": "Mac Studio",
            "attest_public_keys": [b64(seq(0xa0))],
            "wrap_public_key": b64(fill(0xc1)),
            "peer_protocol": 1,
            "product_version": "1.27.0",
        },
        "card_b": {
            "node_id": "00000000-0000-4000-8000-00000000000b",
            "name": "vps",
            "attest_public_keys": [b64(fill(0xb1)), b64(fill(0xb2))],
            "wrap_public_key": b64(fill(0xb3)),
            "peer_protocol": 1,
            "product_version": "1.26.2",
        },
        "rotation": {"next_spki": seq(0x80).hex(), "peer_spki": seq(0x20).hex(),
                     "node_id": "00000000-0000-4000-8000-00000000000a", "counter": 2},
    }
    spki_a, spki_b = bytes.fromhex(inputs["spki_a"]), bytes.fromhex(inputs["spki_b"])
    nonce_a, nonce_b = bytes.fromhex(inputs["nonce_a"]), bytes.fromhex(inputs["nonce_b"])
    ca, cb = card_bytes(inputs["card_a"]), card_bytes(inputs["card_b"])
    digest = sha(SAS_DOMAIN + spki_b + spki_a + nonce_a + nonce_b + sha(ca) + sha(cb))
    rot = inputs["rotation"]
    rotate = (ROTATE_DOMAIN + bytes.fromhex(rot["next_spki"]) + bytes.fromhex(rot["peer_spki"]) + lp(rot["node_id"])
              + rot["counter"].to_bytes(8, "big"))
    return {
        "$comment": "design/peers/link.md pairing vector. Generated by tools/dev/peer_pairing_vectors.py --write; "
                    "asserted by PeerCryptoVectors (core/tests/unit/test_peer_crypto.cpp).",
        "inputs": inputs,
        "expected": {
            "card_a_bytes": ca.hex(),
            "card_a_sha256": sha(ca).hex(),
            "card_b_sha256": sha(cb).hex(),
            "commitment_a": sha(COMMIT_DOMAIN + spki_a + nonce_a).hex(),
            "sas_digest": digest.hex(),
            "code": code_of(digest),
            "rotation_message": rotate.hex(),
        },
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    doc = build()
    text = json.dumps(doc, indent=2) + "\n"
    if args.write:
        VECTORS.parent.mkdir(parents=True, exist_ok=True)
        VECTORS.write_text(text)
        return 0
    current = VECTORS.read_text() if VECTORS.exists() else ""
    if current != text:
        print(f"{VECTORS} differs from what the reference computes; run --write and review", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
