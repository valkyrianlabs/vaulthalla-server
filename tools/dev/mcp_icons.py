#!/usr/bin/env python3
"""Regenerate core/usage/src/mcp/Icons.cpp: the MCP server's icons (serverInfo.icons, MCP 2025-11-25) as base64 of
core/usage/assets/vaulthalla-{64,128}.png, compiled in so `vh mcp` answers with the daemon down. Those PNGs are the
console's icon (web/src/app/icon.png) scaled down. McpServer.IconsAreTheAssetsBytes holds the two together.

  tools/dev/mcp_icons.py          write the file
  tools/dev/mcp_icons.py --check  exit 1 when it is stale
Standard library only.
"""

from __future__ import annotations

import base64
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "core" / "usage" / "assets"
OUT = ROOT / "core" / "usage" / "src" / "mcp" / "Icons.cpp"
SIZES = (64, 128)


def literal(data: bytes) -> str:
    text = base64.b64encode(data).decode("ascii")
    return "\n".join(f'        "{text[i:i + 100]}"' for i in range(0, len(text), 100))


def render() -> str:
    parts = [
        "// Generated by tools/dev/mcp_icons.py from core/usage/assets/vaulthalla-{64,128}.png; do not edit.",
        "",
        '#include "Mcp.hpp"',
        "",
        "namespace vh::mcp {",
        "",
        "const std::vector<Icon>& icons() {",
        "    static const std::vector<Icon> list{",
    ]
    for size in SIZES:
        data = (ASSETS / f"vaulthalla-{size}.png").read_bytes()
        parts.append(f'        {{.png_base64 =\n{literal(data)},\n         .size = {size}}},')
    parts += ["    };", "    return list;", "}", "", "}", ""]
    return "\n".join(parts)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run tools/dev/mcp_icons.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
