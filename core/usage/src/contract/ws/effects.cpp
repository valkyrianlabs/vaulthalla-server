// What each ws command does (design/core/mcp-remote-signin.md, "Scoped devices"): read (changes nothing), write
// (changes state that can be changed back) or destructive (deletes, purges, revokes, rotates or can't be undone) -- the
// CLI leaves' CommandEffect rule. A scoped device's session runs only commands within its scope
// (protocols::ws::Router, data.code device_scope); every command in the book has exactly one row here
// (UsageContract.EveryWsCommandDeclaresAnEffect), applied by commands() and exported as `effect`. Where a command's
// effect is ambiguous it takes the higher one, as its CLI leaf does: unassigning, unbinding, removing an override or a
// member, clearing a default role, revoking a role, disabling a budget policy or upstream administration/events
// and aborting an attach are destructive. Cancelling one's own upload stays write: it discards only bytes the same
// session sent and never committed.

